"""Copy validation-only parity images and exact FLOAT32 model inputs."""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import random
import shutil
from predict import load_model
from train_baseline import load_image


def main(args):
    interpreter,inp,out,manifest=load_model(args.assets)
    rows=list(csv.DictReader(Path(args.manifest).open(encoding="utf-8")))
    fixtures=[]
    destination=Path(args.fixture_assets)/"parity_images"
    destination.mkdir(parents=True,exist_ok=True)
    for label in manifest["labels"]:
        candidates=[r for r in rows if r["split"]=="validation" and r["label"]==label]
        random.Random(20261012).shuffle(candidates)
        if len(candidates)<2: raise ValueError("Two validation examples per class required")
        for i,row in enumerate(candidates[:2]):
            source=Path(args.dataset)/row["path"]
            name=f"{label.lower()}_{i+1}.jpg"
            shutil.copyfile(source,destination/name)
            image=load_image(source)[None,...]
            interpreter.set_tensor(inp["index"],image);interpreter.invoke()
            probabilities=interpreter.get_tensor(out["index"])[0].tolist()
            tensor=image.astype("<f4").tobytes(order="C")
            tensor_name=name.replace(".jpg",".f32")
            (destination/tensor_name).write_bytes(tensor)
            fixtures.append({"image_file":"parity_images/"+name,"input_file":"parity_images/"+tensor_name,"input_encoding":"little_endian_float32_row_major_NHWC","input_shape":[1,224,224,3],"source_path":row["path"],"source_split":"validation","source_class":row["label"],"source_sha256":row["sha256"],"input_sha256":hashlib.sha256(tensor).hexdigest(),"probabilities":probabilities})
    path=Path(args.fixture_assets)/"parity_fixtures.json"
    report=json.loads(path.read_text())
    report.update(natural_fixtures=fixtures,natural_fixture_tensor_probability_tolerance=.002,natural_fixture_preprocessing_input_tolerance=2/127.5,natural_fixture_notes="Expected tensors use Pillow bilinear downsampling and EXIF transpose. Raw tensor runtime tolerance0.002 applies only to identical inputs. Natural JPEG decoding/resizing parity must be measured on Android; these tolerances are proposed acceptance limits, not verified device results. Samples from validation only; no held-out test was queried.")
    path.write_text(json.dumps(report,indent=2),encoding="utf-8")
    (destination/"ATTRIBUTION.md").write_text("# Validation parity fixtures\n\nSource candidate: Arifen et al., Large-Scale Lemon Leaf Disease and Pest Image Dataset from Bangladesh, Mendeley Data v2, DOI 10.17632/8d9fv6kpt3.2, https://data.mendeley.com/datasets/8d9fv6kpt3/2 . Public license CC BY4.0. Local copy provenance still pending confirmation. Four unmodified validation JPEGs copied for reproducibility; derived FLOAT32 tensors generated by EXIF transpose, RGB bilinear resize and RGB/127.5-1. Not LIMONORT images, not confirmed limón sutil or early damage. No independent agricultural validation is inferred.\n",encoding="utf-8")
    print(json.dumps({"fixtures":len(fixtures),"dataset_split":"validation","model_sha256":manifest["model_sha256"]}))


if __name__=="__main__":
    p=argparse.ArgumentParser();p.add_argument("--dataset",required=True);p.add_argument("--manifest",default="ml/artifacts/manifest.csv");p.add_argument("--assets",default="app/src/main/assets/models")
    p.add_argument("--fixture-assets",default="app/src/androidTest/assets/models")
    main(p.parse_args())
